#add items- we need add() method to add items into sets.
thisset={"apple","banana","cherry"}
thisset.add("Orange")
print(thisset)

#add sets-add items from one set to another set, update().
tropical={"Mango","seethaphal"}
thisset.update(tropical)
print(thisset)

#update() method is even used to add set to other built in types. 
