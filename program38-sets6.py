#FrozenSet- Its an immutable version of sets. 
#Unlike sets, elements or values can't be added or removed from frozen set.
#To create a frozenset, we need to use frozenset() constructor.
x=frozenset({"apple","kiwi","cherry"})
print(x)
print(type(x))

