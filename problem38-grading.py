#Grade to Description Mapping
#Write a program in Python to accept a grade and declare the equivalent
#description :
a=input("select from E,V,G,A,F:")
if a=='E':
    print("Excellent")
elif a=='V':
    print("Very good")
elif a=='G':
    print("Good")
elif a=='A':
    print("Average")
elif a=='F':
    print("Fail")
else:
    print("Unknown grade")